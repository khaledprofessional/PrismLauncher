void HyperMinePage::onSavePanelClicked()
{
    auto* settings = APPLICATION->settings();
    const QString address = ui->addressEdit->text().trimmed();
    if (!address.isEmpty()) {
        const QUrl url(address);
        if (!url.isValid() || url.host().isEmpty()) {
            CustomMessageBox::selectable(this, tr("That address is not usable"),
                                          tr("'%1' is not a valid URL. It needs to look like http://10.13.0.1:8080.")
                                              .arg(address))
                ->show();
            return;
        }
    }
    settings->set(kPanelUrlKey, address);
    settings->set(kPanelTokenKey, ui->tokenEdit->text());
    settings->set(kAutoTunnelKey, ui->autoTunnelCheck->isChecked());
    applyPanelSettings();
    appendLog(tr("Saved the panel settings."));
}

void HyperMinePage::applyPanelSettings()
{
    const QString address = ui->addressEdit->text().trimmed();
    m_client->setBaseUrl(address.isEmpty() ? QUrl{} : QUrl(address));
    m_client->setToken(ui->tokenEdit->text());
    // isHandshakeFresh, not hasHandshake: a tunnel that handshaked an hour ago and then
    // went stale is exactly the case the client's guard exists to catch, and "has
    // handshaked once" would wave it through.
    m_client->setTunnelUp(m_tunnel->isUp() && m_tunnel->isHandshakeFresh());
    refreshPanelAvailability();
}

