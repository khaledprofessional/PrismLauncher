void HyperMinePage::reload()
{
    loadTunnelFromSettings();

    auto* settings = APPLICATION->settings();
    ui->addressEdit->setText(settings->get(kPanelUrlKey).toString());
    ui->tokenEdit->setText(settings->get(kPanelTokenKey).toString());
    // QVariant::toBool() takes no default in Qt 6, so the default lives here. An unset
    // setting comes back as an invalid QVariant, which is what opts for "on".
    const QVariant autoTunnel = settings->get(kAutoTunnelKey);
    ui->autoTunnelCheck->setChecked(autoTunnel.isValid() ? autoTunnel.toBool() : true);

    // An address that was never set by hand follows the tunnel, which is where the panel
    // is expected to be. One that was set by hand is left alone.
    if (ui->addressEdit->text().isEmpty()) {
        const QUrl suggested = suggestedPanelUrl();
        if (suggested.isValid()) {
            ui->addressEdit->setPlaceholderText(suggested.toString());
        }
    }

    populateInstances();
    // Push the loaded address and token into the client straight away. Without this the
    // tab opens showing "no panel address configured" and a disabled Refresh button even
    // though a perfectly good address is saved, until the user presses Save by hand.
    applyPanelSettings();
    refreshTunnelLabels();
    refreshPlayAddress();
}

void HyperMinePage::loadTunnelFromSettings()
{
    const QString confPath = APPLICATION->settings()->get(kConfPathKey).toString();
    if (confPath.isEmpty()) {
        m_tunnel->clearInterface();
        return;
    }

    QFile file(confPath);
    if (!file.open(QIODevice::ReadOnly | QIODevice::Text)) {
        // Not fatal: the tab is still usable, it just has no tunnel until one is imported.
        m_tunnel->clearInterface();
        appendLog(tr("Could not reopen %1: %2").arg(confPath, file.errorString()));
        return;
    }
    const QString text = QString::fromUtf8(file.readAll());
    file.close();

    // The interface name comes from the file name, which is what wg-quick and
    // wireguard.exe both use to name the tunnel.
    const QString name = QFileInfo(confPath).completeBaseName();
    QString error;
    const WireGuardInterface iface = WireGuardInterface::fromConf(text, name, &error);
    if (iface.name.isEmpty()) {
        m_tunnel->clearInterface();
        appendLog(tr("Ignoring %1: %2").arg(confPath, error));
        return;
    }
    m_tunnel->setInterface(iface);
    m_tunnel->refresh();
}

void HyperMinePage::saveTunnelToSettings(const QString& confPath)
{
    APPLICATION->settings()->set(kConfPathKey, confPath);
}

void HyperMinePage::activate()
{
    if (ui->autoTunnelCheck->isChecked() && m_tunnel->hasInterface() && !m_tunnel->isUp()) {
        m_tunnel->bringUp();
    }
    if (m_client->canSend()) {
        m_client->fetchServers();
    }
}

void HyperMinePage::onImportClicked()
{
    const QString path = QFileDialog::getOpenFileName(this, tr("Import a WireGuard configuration"), QString(),
                                                      tr("WireGuard configurations (*.conf);;All files (*)"));
    if (path.isEmpty()) {
        return;
    }

    QFile file(path);
    if (!file.open(QIODevice::ReadOnly | QIODevice::Text)) {
        CustomMessageBox::selectable(this, tr("Could not read the configuration"),
                                      tr("Could not open %1: %2").arg(path, file.errorString()))
            ->show();
        return;
    }
    const QString text = QString::fromUtf8(file.readAll());
    file.close();

    const QString name = QFileInfo(path).completeBaseName();
    QString error;
    const WireGuardInterface iface = WireGuardInterface::fromConf(text, name, &error);
    if (iface.name.isEmpty()) {
        // The reason is shown rather than swallowed: a config that looks fine but has,
        // say, a truncated key is otherwise a silent no-op.
        CustomMessageBox::selectable(this, tr("That configuration cannot be used"), error)->show();
        return;
    }

    m_tunnel->setInterface(iface);
    // Persist the canonical copy the tunnel actually uses, not the file the user picked.
    // Importing from a USB stick and then re-reading that same stick on next launch would
    // leave the copy under dataRoot orphaned and silently follow the original around.
    saveTunnelToSettings(m_tunnel->confPath());
    appendLog(tr("Imported the %1 tunnel from %2").arg(iface.name, path));

    // A newly imported tunnel usually means a new panel address, so offer the derived one.
    const QUrl suggested = suggestedPanelUrl();
    if (ui->addressEdit->text().isEmpty() && suggested.isValid()) {
        ui->addressEdit->setText(suggested.toString());
        APPLICATION->settings()->set(kPanelUrlKey, suggested.toString());
    }

    refreshTunnelLabels();
    // The derived address above was written to the widget and to settings; push it into
    // the client too, or the panel buttons stay disabled until the user presses Save.
    applyPanelSettings();
    refreshPlayAddress();

    if (ui->autoTunnelCheck->isChecked()) {
        m_tunnel->bringUp();
    }
}

void HyperMinePage::onForgetClicked()
{
    clearPendingPlay();
    // forget() tears the tunnel down before discarding the config. Doing it the other
    // way round here would cancel the uninstall half-way and leave the interface
    // installed with nothing left to manage it.
    m_tunnel->forget();
    APPLICATION->settings()->set(kConfPathKey, QString());
    appendLog(tr("Forgot the imported tunnel."));
    refreshTunnelLabels();
    refreshPanelAvailability();
    refreshPlayAddress();
}

